	PROGRAM GRID

	INTEGER I, COL, COLUMN( 16 )
	CHARACTER BLANK, ROW( 16 ), QUEEN, TOP( 33 )
	PARAMETER( QUEEN = 'Q', BLANK = '_' )
	DATA TOP/ 33*'_'/

	PRINT *, 'ENTER 16 DIGITS, 1 - 16 : '
	READ *, COLUMN

	PRINT *, TOP
	DO 22 I = 1, 16
	   DO 11 COL = 1, 16
	      ROW( COL ) = BLANK
11	   CONTINUE
	   COL = COLUMN( I )
	   ROW( COL ) = QUEEN
	   PRINT *, ('|',ROW(COL),COL=1,16),'|'
22	CONTINUE

	END
